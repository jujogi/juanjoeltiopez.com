// Funciones helper
export function getAllVideos() {
  return videos;
}

export function getVideoById(id) {
  return videos.find(video => video.id === id);
}

export function getVideosByIds(ids) {
  if (!ids || ids.length === 0) return [];
  return ids.map(id => getVideoById(id)).filter(Boolean);
}

export function getVideosByTag(tag) {
  return videos.filter(video => video.tags && video.tags.includes(tag));
}

export function getVideosByTags(tags) {
  if (!tags || tags.length === 0) return [];
  return videos.filter(video => video.tags && tags.some(tag => video.tags.includes(tag)));
}
